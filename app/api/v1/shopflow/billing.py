"""
ShopFlow Billing and Bills Endpoints.
"""

from datetime import datetime
from typing import Annotated
from uuid import UUID
from fastapi import APIRouter, Depends, Query

from app.core import permissions as perm_constants
from app.core.dependencies import require_any_permission
from app.integrations.shopflow.client import ShopFlowClient, get_shopflow_client
from app.integrations.shopflow.schemas import (
    CloudBillListResponse,
    CloudShopBillingSummary,
)
from app.models.cloud_user import CloudUser

router = APIRouter(tags=["ShopFlow - Billing & Bills"])

ReadAuthDep = Annotated[
    CloudUser,
    Depends(require_any_permission(perm_constants.SHOPFLOW_READ, perm_constants.DASHBOARD_VIEW)),
]


@router.get("/shops/{tenant_id}/billing/summary", response_model=CloudShopBillingSummary)
async def get_shop_billing_summary(
    tenant_id: UUID,
    _current_user: ReadAuthDep,
    client: Annotated[ShopFlowClient, Depends(get_shopflow_client)],
) -> CloudShopBillingSummary:
    """Retrieve financial summary for a specific shop."""
    return await client.get_shop_billing_summary(tenant_id)


@router.get("/shops/{tenant_id}/billing/bills", response_model=CloudBillListResponse)
async def list_shop_bills(
    tenant_id: UUID,
    _current_user: ReadAuthDep,
    client: Annotated[ShopFlowClient, Depends(get_shopflow_client)],
    limit: int = Query(50, ge=1, le=100),
    offset: int = Query(0, ge=0),
    status: str | None = Query(None),
    start_date: datetime | None = Query(None),
    end_date: datetime | None = Query(None),
) -> CloudBillListResponse:
    """List bills generated by a specific shop with filtering."""
    return await client.list_shop_bills(
        tenant_id=tenant_id,
        limit=limit,
        offset=offset,
        status=status,
        start_date=start_date,
        end_date=end_date,
    )


@router.get("/billing/bills", response_model=CloudBillListResponse)
async def list_all_bills(
    _current_user: ReadAuthDep,
    client: Annotated[ShopFlowClient, Depends(get_shopflow_client)],
    limit: int = Query(50, ge=1, le=100),
    offset: int = Query(0, ge=0),
    status: str | None = Query(None),
    start_date: datetime | None = Query(None),
    end_date: datetime | None = Query(None),
) -> CloudBillListResponse:
    """List bills across all shops for platform-level auditing and reconciliation."""
    return await client.list_all_bills(
        limit=limit,
        offset=offset,
        status=status,
        start_date=start_date,
        end_date=end_date,
    )
